  final list = source.split('kWashGalleryPageIds').last;
  return re
      .allMatches(list)
      .map((m) => m.group(1)!)
      .where((s) => s != 'kWashGalleryPageIds')
      .toList();
}

Map<String, String> _pageToTsxPath(String appTsx, String demoSrc) {
  final lazy = RegExp(r"const (\w+) = lazy\(\(\) => import\('\./([^']+)'\)\)");
  final componentToFile = <String, String>{};
  for (final m in lazy.allMatches(appTsx)) {
    componentToFile[m.group(1)!] = '$demoSrc/${m.group(2)!}.tsx';
  }
  final caseRe = RegExp(r"case '([^']+)':\s*\n\s*return <(\w+)");
  final map = <String, String>{};
  for (final m in caseRe.allMatches(appTsx)) {
    final page = m.group(1)!;
    final component = m.group(2)!;
    final path = componentToFile[component];
    if (path != null && File(path).existsSync()) {
      map[page] = path;
    }
  }
  final suspenseRe = RegExp(r"case '([^']+)':[\s\S]*?<(\w+Page)\s*/>");
  for (final m in suspenseRe.allMatches(appTsx)) {
    final page = m.group(1)!;
    final component = m.group(2)!;
    final path = componentToFile[component];
    if (path != null && File(path).existsSync()) {
      map[page] = path;
    }
  }
  for (final entry in _tsxOverrides(demoSrc).entries) {
    if (File(entry.value).existsSync()) {
      map[entry.key] = entry.value;
    }
  }
  map['overview'] = '$demoSrc/OverviewPage.tsx';
  map['support'] = '$demoSrc/SupportPage.tsx';
  for (final lang in _lspLangs) {
    map['lsp-$lang'] = '$demoSrc/components/IconLibraryPage.tsx';
  }
  return map;
}

