Map<String, String> _parseSubtitles(String appTsx) {
  final re = RegExp(r"'([^']+)':\s*'((?:\\'|[^'])*)'");
  final start = appTsx.indexOf('const pageSubtitle');
  if (start < 0) return {};
  final end = (start + 120000).clamp(0, appTsx.length);
  final slice = appTsx.substring(start, end);
  final map = <String, String>{};
  for (final m in re.allMatches(slice)) {
    map[m.group(1)!] = m.group(2)!;
  }
  return map;
}

class _Section {
  _Section({
    required this.eyebrow,
    required this.title,
    this.description,
    this.tint,
  });
  final String eyebrow;
  final String title;
  final String? description;
  final String? tint;
}

List<_Section> _parseSections(String tsx) {
  final re = RegExp(r'<GallerySection\s+([^>]+)>', multiLine: true);
  final sections = <_Section>[];
  for (final m in re.allMatches(tsx)) {
    final attrs = m.group(1)!;
    sections.add(
      _Section(
        eyebrow: _attr(attrs, 'eyebrow') ?? 'Section',
        title: _attr(attrs, 'title') ?? 'Untitled',
        description: _attr(attrs, 'description'),
        tint: _attr(attrs, 'panel'),
      ),
    );
  }
  if (sections.isEmpty) {
    sections.add(
      _Section(eyebrow: 'Preview', title: 'Live demo', description: null),
    );
  }
  return sections;
}

String? _attr(String attrs, String name) {
  final re = RegExp('$name="([^"]*)"');
  return re.firstMatch(attrs)?.group(1);
}

(String, String) _parseHero(
  String tsx,
  String id,
  Map<String, String> subtitles,
) {
  final h1 = RegExp(
    r'<h1[^>]*>\s*([^<]+)\s*</h1>',
    multiLine: true,
  ).firstMatch(tsx)?.group(1)?.trim();
  var desc = RegExp(
    r'max-w-2xl[^"]*"[^>]*>\s*([\s\S]*?)\s*</p>',
    multiLine: true,
  ).firstMatch(tsx)?.group(1)?.replaceAll(RegExp(r'<[^>]+>'), '');
  desc = desc
      ?.replaceAll(RegExp(r"\{[^}]*\}"), '')
      .replaceAll(RegExp(r'\s+'), ' ')
      .trim();
  final title = h1 ?? _titleFromId(id);
  var description = desc ?? subtitles[id] ?? 'Wash UI gallery preview.';
  if (description.length > 200 ||
      description.contains('`') ||
      description.contains('className')) {
    description = subtitles[id] ?? 'Wash UI gallery preview.';
  }
  return (title, description);
}

const _titleOverrides = <String, String>{
  'template-code-editor': 'Code editor',
  'template-docs-layout': 'Documentation layout',
};

String _titleFromId(String id) => id
    .split('-')
    .map((p) => p.isEmpty ? p : '${p[0].toUpperCase()}${p.substring(1)}')
    .join(' ');

String? _parseKicker(String tsx) {
  final pattern = RegExp(
    r'<p[^>]*className="label-ink mb-2"[^>]*>\s*([\s\S]*?)\s*</p>',
  );
  for (final match in pattern.allMatches(tsx)) {
    final end = match.end + 600 < tsx.length ? match.end + 600 : tsx.length;
    if (!tsx.substring(match.end, end).contains('<h1')) continue;
    final text = match
        .group(1)
        ?.replaceAll(RegExp(r'<[^>]+>'), '')
        .replaceAll(RegExp(r'\s+'), ' ')
        .trim();
    if (text == null || text.isEmpty || text.contains('{')) continue;
    return text;
  }
  return null;
}

String _emitPage(
  String className,
  String pageId,
  String title,
  String description,
  List<_Section> sections, {
  bool chart = false,
  bool template = false,
  bool behaviour = false,
  String? kicker,
}) {
  final b = StringBuffer();
  b.writeln('// GENERATED by tool/generate_gallery_pages.dart');
  b.writeln("import 'package:flutter/widgets.dart';");
  b.writeln();
  if (chart) {
    b.writeln("import '../../wash_gallery_chart.dart';");
  } else if (template) {
    b.writeln("import '../../wash_template_preview.dart';");
  } else if (behaviour) {
    b.writeln("import '../../wash_behaviour_preview.dart';");
  } else {
    b.writeln("import '../../wash_gallery_legacy_preview.dart';");
  }
  b.writeln("import '../../wash_gallery_panel.dart';");
  b.writeln("import '../../wash_showcase_tabs.dart';");
  b.writeln();
  b.writeln('class $className extends StatelessWidget {');
  b.writeln('  const $className({super.key});');
  b.writeln();
  b.writeln('  @override');
  b.writeln('  Widget build(BuildContext context) {');
  b.writeln('    return WashGalleryPage(');
  if (kicker != null && kicker != 'Component gallery') {
    b.writeln("      kicker: ${_q(kicker)},");
  }
  b.writeln("      title: ${_q(title)},");
  b.writeln("      description: ${_q(description)},");
  b.writeln('      sections: [');
  for (var i = 0; i < sections.length; i++) {
    final s = sections[i];
    final tint = switch (s.tint) {
      'wash-panel-ochre' => 'WashGalleryPanelTint.ochre',
      'wash-panel-rose' => 'WashGalleryPanelTint.rose',
      _ => 'WashGalleryPanelTint.none',
    };
    b.writeln('        WashGallerySection(');
    b.writeln("          eyebrow: ${_q(s.eyebrow)},");
    b.writeln("          title: ${_q(s.title)},");
    if (s.description != null) {
      b.writeln("          description: ${_q(s.description!)},");
    }
    if (tint != 'WashGalleryPanelTint.none') {
      b.writeln('          tint: $tint,');
    }
    b.writeln('          child: WashShowcaseTabs(');
    if (chart) {
      b.writeln(
        "            preview: WashGalleryChart(categoryId: '$pageId', sectionIndex: ${i + 1}, sectionTitle: ${_q(s.title)}),",
      );
    } else if (template) {
      b.writeln(
        "            preview: WashTemplatePreview(pageId: '$pageId', sectionIndex: ${i + 1}, sectionTitle: ${_q(s.title)}),",
      );
    } else if (behaviour) {
      b.writeln(
        "            preview: WashBehaviourPreview(pageId: '$pageId', sectionIndex: ${i + 1}, sectionTitle: ${_q(s.title)}),",
      );
    } else {
      b.writeln(
        "            preview: WashGalleryLegacyPreview.build(context, '$pageId'),",
      );
    }
    b.writeln(
      '            dartSource: ${_q('// Preview section ${i + 1}: ${s.title}\nWashGalleryLegacyPreview.build(context, \'$pageId\');')},',
    );
    b.writeln('          ),');
    b.writeln('        ),');
  }
  b.writeln('      ],');
  b.writeln('    );');
  b.writeln('  }');
  b.writeln('}');
  return b.toString();
}

String _q(String s) {
  final cleaned = s
      .replaceAll('\n', ' ')
      .replaceAll(RegExp(r'\s+'), ' ')
      .trim();
  final escaped = cleaned.replaceAll(r'\', r'\\').replaceAll("'", r"\'");
  return "'$escaped'";
}

String _escapeComment(String s) => s.replaceAll('\n', ' ');

String _classNameFor(String id) {
  final parts = id.split('-').map((p) {
    if (p.isEmpty) return '';
    return '${p[0].toUpperCase()}${p.substring(1)}';
  });
  return 'Wash${parts.join()}GalleryPage';
}

String _snakeCase(String className) {
  final buf = StringBuffer();
  for (var i = 0; i < className.length; i++) {
    final c = className[i];
    if (c == c.toUpperCase() && i > 0) buf.write('_');
    buf.write(c.toLowerCase());
  }
  return buf.toString();
}

