String _repoRoot() {
  var dir = Directory.current;
  while (!File('${dir.path}/pubspec.yaml').existsSync() &&
      !File('${dir.path}/package.json').existsSync()) {
    dir = dir.parent;
  }
  if (File('${dir.path}/package.json').existsSync()) return dir.path;
  return dir.parent.path;
}
