// ignore_for_file: avoid_print
import 'dart:io';

/// Parses daisyUI theme blocks from Wash themes.css into Dart.
void main(List<String> args) {
  final repoRoot = _findRepoRoot();
  final cssPath = args.isNotEmpty
      ? args.first
      : '$repoRoot/packages/menzies-design-wash-ui/src/styles/themes.css';
  final outPath = args.length > 1
      ? args[1]
      : '$repoRoot/packages/menzies_design_wash_ui/lib/src/tokens/wash_pigments.g.dart';

  final css = File(cssPath).readAsStringSync();
  final themes = _parseThemes(css);
  if (themes.isEmpty) {
    stderr.writeln('No themes parsed from $cssPath');
    exit(1);
  }

  final buffer = StringBuffer();
  buffer.writeln('// GENERATED by tool/wash_tokens/generate.dart — do not edit.');
  buffer.writeln();
  buffer.writeln("import 'dart:ui' show Color;");
  buffer.writeln();
  buffer.writeln('/// Single pigment palette (daisyUI semantic colors).');
  buffer.writeln('class WashPigmentPalette {');
  buffer.writeln('  const WashPigmentPalette({');
  buffer.writeln('    required this.id,');
  buffer.writeln('    required this.isDark,');
  buffer.writeln('    required this.base100,');
  buffer.writeln('    required this.base200,');
  buffer.writeln('    required this.base300,');
  buffer.writeln('    required this.baseContent,');
  buffer.writeln('    required this.primary,');
  buffer.writeln('    required this.primaryContent,');
  buffer.writeln('    required this.secondary,');
  buffer.writeln('    required this.secondaryContent,');
  buffer.writeln('    required this.accent,');
  buffer.writeln('    required this.accentContent,');
  buffer.writeln('    required this.neutral,');
  buffer.writeln('    required this.neutralContent,');
  buffer.writeln('    required this.info,');
  buffer.writeln('    required this.infoContent,');
  buffer.writeln('    required this.success,');
  buffer.writeln('    required this.successContent,');
  buffer.writeln('    required this.warning,');
  buffer.writeln('    required this.warningContent,');
  buffer.writeln('    required this.error,');
  buffer.writeln('    required this.errorContent,');
  buffer.writeln('    required this.radiusSelector,');
  buffer.writeln('    required this.radiusField,');
  buffer.writeln('    required this.radiusBox,');
  buffer.writeln('  });');
  buffer.writeln();
  buffer.writeln('  final String id;');
  buffer.writeln('  final bool isDark;');
  buffer.writeln('  final Color base100;');
  buffer.writeln('  final Color base200;');
  buffer.writeln('  final Color base300;');
  buffer.writeln('  final Color baseContent;');
  buffer.writeln('  final Color primary;');
  buffer.writeln('  final Color primaryContent;');
  buffer.writeln('  final Color secondary;');
  buffer.writeln('  final Color secondaryContent;');
  buffer.writeln('  final Color accent;');
  buffer.writeln('  final Color accentContent;');
  buffer.writeln('  final Color neutral;');
  buffer.writeln('  final Color neutralContent;');
  buffer.writeln('  final Color info;');
  buffer.writeln('  final Color infoContent;');
  buffer.writeln('  final Color success;');
  buffer.writeln('  final Color successContent;');
  buffer.writeln('  final Color warning;');
  buffer.writeln('  final Color warningContent;');
  buffer.writeln('  final Color error;');
  buffer.writeln('  final Color errorContent;');
  buffer.writeln('  final double radiusSelector;');
  buffer.writeln('  final double radiusField;');
  buffer.writeln('  final double radiusBox;');
  buffer.writeln('}');
  buffer.writeln();
  buffer.writeln('int _hex(String hex) {');
  buffer.writeln('  var h = hex.replaceAll("#", "");');
  buffer.writeln(r'  if (h.length == 6) h = "ff" + h;');
  buffer.writeln('  return int.parse(h, radix: 16);');
  buffer.writeln('}');
  buffer.writeln();
  buffer.writeln('final Map<String, WashPigmentPalette> kWashPigmentPalettes = {');

  for (final t in themes) {
    buffer.writeln("  '${t.id}': WashPigmentPalette(");
    buffer.writeln("    id: '${t.id}',");
    buffer.writeln('    isDark: ${t.isDark},');
    for (final entry in t.colors.entries) {
      buffer.writeln(
        '    ${entry.key}: Color(_hex("${entry.value}")),',
      );
    }
    for (final entry in t.radii.entries) {
      buffer.writeln('    ${entry.key}: ${entry.value},');
    }
    buffer.writeln('  ),');
  }
  buffer.writeln('};');
  buffer.writeln();
  buffer.writeln('/// Base pigment ids (light), without `-dark` suffix.');
  buffer.writeln('const List<String> kWashPigmentIds = [');
  final lightIds = themes
      .where((t) => !t.isDark)
      .map((t) => t.id)
      .toList();
  for (final id in lightIds) {
    buffer.writeln("  '$id',");
  }
  buffer.writeln('];');
  buffer.writeln();
  buffer.writeln('int get kWashPigmentPaletteCount => kWashPigmentPalettes.length;');

  File(outPath).parent.createSync(recursive: true);
  File(outPath).writeAsStringSync(buffer.toString());
  print('Wrote ${themes.length} palettes to $outPath');
}

String _findRepoRoot() {
  var dir = Directory.current;
  while (true) {
    if (File('${dir.path}/package.json').existsSync()) {
      return dir.path;
    }
    final parent = dir.parent;
    if (parent.path == dir.path) {
      return Directory.current.path;
    }
    dir = parent;
  }
}

class _ThemeData {
  _ThemeData({
    required this.id,
    required this.isDark,
    required this.colors,
    required this.radii,
  });

  final String id;
  final bool isDark;
  final Map<String, String> colors;
  final Map<String, double> radii;
}

List<_ThemeData> _parseThemes(String css) {
  final themes = <_ThemeData>[];
  final blockRe = RegExp(
    r'@plugin\s+"daisyui/theme"\s*\{([^}]+)\}',
    multiLine: true,
  );
  for (final match in blockRe.allMatches(css)) {
    final body = match.group(1)!;
    final nameMatch = RegExp(r'name:\s*"([^"]+)"').firstMatch(body);
    if (nameMatch == null) continue;
    final name = nameMatch.group(1)!;
    final isDark = name.endsWith('-dark');
    final colors = <String, String>{};
    final radii = <String, double>{};

    void pickColor(String cssVar, String field) {
      final m = RegExp('$cssVar:\\s*(#[0-9a-fA-F]+)').firstMatch(body);
      if (m != null) colors[field] = m.group(1)!;
    }

    pickColor('--color-base-100', 'base100');
    pickColor('--color-base-200', 'base200');
    pickColor('--color-base-300', 'base300');
    pickColor('--color-base-content', 'baseContent');
    pickColor('--color-primary', 'primary');
    pickColor('--color-primary-content', 'primaryContent');
    pickColor('--color-secondary', 'secondary');
    pickColor('--color-secondary-content', 'secondaryContent');
    pickColor('--color-accent', 'accent');
    pickColor('--color-accent-content', 'accentContent');
    pickColor('--color-neutral', 'neutral');
    pickColor('--color-neutral-content', 'neutralContent');
    pickColor('--color-info', 'info');
    pickColor('--color-info-content', 'infoContent');
    pickColor('--color-success', 'success');
    pickColor('--color-success-content', 'successContent');
    pickColor('--color-warning', 'warning');
    pickColor('--color-warning-content', 'warningContent');
    pickColor('--color-error', 'error');
    pickColor('--color-error-content', 'errorContent');

    double? pickRem(String cssVar, String field) {
      final m = RegExp('$cssVar:\\s*([0-9.]+)rem').firstMatch(body);
      if (m == null) return null;
      radii[field] = double.parse(m.group(1)!) * 16;
      return radii[field];
    }

    pickRem('--radius-selector', 'radiusSelector');
    pickRem('--radius-field', 'radiusField');
    pickRem('--radius-box', 'radiusBox');

    if (colors.length < 10) continue;
    themes.add(
      _ThemeData(id: name, isDark: isDark, colors: colors, radii: radii),
    );
  }
  return themes;
}
