// ignore_for_file: avoid_print
import 'dart:convert';
import 'dart:io';

/// Mirrors the web getting-started stack data into Dart so the Flutter docs
/// family stays in lockstep with `apps/demo/src/data/getting-started-stacks.ts`.
void main() {
  final repo = _repoRoot();
  final result = Process.runSync('node', [
    '--experimental-strip-types',
    '-e',
    "import('./apps/demo/src/data/getting-started-stacks.ts')"
        ".then(m => process.stdout.write(JSON.stringify(m.gettingStartedStacks)))",
  ], workingDirectory: repo);
  if (result.exitCode != 0) {
    stderr.writeln(result.stderr);
    exit(result.exitCode);
  }
  final stacks = jsonDecode(result.stdout as String) as List<dynamic>;
  final b = StringBuffer();
  b.writeln('// GENERATED by tool/generate_docs_data.dart');
  b.writeln('// Source: apps/demo/src/data/getting-started-stacks.ts');
  b.writeln();
  b.writeln('class WashDocsStepData {');
  b.writeln('  const WashDocsStepData({');
  b.writeln('    required this.title,');
  b.writeln('    this.body,');
  b.writeln('    this.code,');
  b.writeln('  });');
  b.writeln('  final String title;');
  b.writeln('  final String? body;');
  b.writeln('  final String? code;');
  b.writeln('}');
  b.writeln();
  b.writeln('class WashDocsStackData {');
  b.writeln('  const WashDocsStackData({');
  b.writeln('    required this.id,');
  b.writeln('    required this.page,');
  b.writeln('    required this.name,');
  b.writeln('    required this.description,');
  b.writeln('    required this.adapter,');
  b.writeln('    required this.tone,');
  b.writeln('    required this.steps,');
  b.writeln('    this.notes = const [],');
  b.writeln('  });');
  b.writeln('  final String id;');
  b.writeln('  final String page;');
  b.writeln('  final String name;');
  b.writeln('  final String description;');
  b.writeln('  final String adapter;');
  b.writeln('  final String tone;');
  b.writeln('  final List<WashDocsStepData> steps;');
  b.writeln('  final List<String> notes;');
  b.writeln('}');
  b.writeln();
  b.writeln(
    'const Map<String, WashDocsStackData> kWashDocsStacks = <String, WashDocsStackData>{',
  );
  for (final raw in stacks) {
    final stack = raw as Map<String, dynamic>;
    final accent = stack['accentClass'] as String? ?? '';
    final toneMatch = RegExp(r'text-([a-z-]+)').firstMatch(accent);
    final tone = switch (toneMatch?.group(1)) {
      'warning' => 'warning',
      'info' => 'info',
      'success' => 'success',
      'error' => 'error',
      'accent' => 'accent',
      'primary' => 'primary',
      'secondary' => 'secondary',
      'neutral' => 'neutral',
      _ => 'neutral',
    };
    b.writeln("  '${stack['id']}': WashDocsStackData(");
    b.writeln("    id: ${_dart(stack['id'] as String)},");
    b.writeln("    page: ${_dart(stack['page'] as String)},");
    b.writeln("    name: ${_dart(stack['name'] as String)},");
    b.writeln("    description: ${_dart(stack['description'] as String)},");
    b.writeln("    adapter: ${_dart(stack['adapter'] as String)},");
    b.writeln("    tone: '$tone',");
    b.writeln('    steps: [');
    for (final rawStep in stack['steps'] as List<dynamic>) {
      final step = rawStep as Map<String, dynamic>;
      b.writeln('      WashDocsStepData(');
      b.writeln('        title: ${_dart(step['title'] as String)},');
      if (step['body'] != null) {
        b.writeln('        body: ${_dart(step['body'] as String)},');
      }
      if (step['code'] != null) {
        b.writeln('        code: ${_dart(step['code'] as String)},');
      }
      b.writeln('      ),');
    }
    b.writeln('    ],');
    final notes = (stack['notes'] as List<dynamic>?) ?? const [];
    if (notes.isNotEmpty) {
      b.writeln('    notes: [');
      for (final note in notes) {
        b.writeln('      ${_dart(note as String)},');
      }
      b.writeln('    ],');
    }
    b.writeln('  ),');
  }
  b.writeln('};');

  final out = File(
    '$repo/packages/menzies_design_wash_ui/lib/src/gallery/wash_docs_data.g.dart',
  )..writeAsStringSync(b.toString());
  print('Generated ${out.path} (${stacks.length} stacks).');
}

String _dart(String value) {
  final escaped = value
      .replaceAll(r'\', r'\\')
      .replaceAll("'", r"\'")
      .replaceAll(r'$', r'\$')
      .replaceAll('\r', '')
      .replaceAll('\n', r'\n');
  return "'$escaped'";
}

String _repoRoot() {
  var dir = Directory.current;
  while (!File('${dir.path}/package.json').existsSync()) {
    dir = dir.parent;
  }
  return dir.path;
}
