// ignore_for_file: avoid_print
import 'dart:io';

/// Parses [data-theme="…"] atmosphere blocks from themes.css.
void main(List<String> args) {
  final root = _repoRoot();
  final cssPath = args.isNotEmpty
      ? args.first
      : '$root/packages/menzies-design-wash-ui/src/styles/themes.css';
  final outPath = args.length > 1
      ? args[1]
      : '$root/packages/menzies_design_wash_ui/lib/src/tokens/wash_atmosphere.g.dart';

  final css = File(cssPath).readAsStringSync();
  final themes = _parseAtmosphere(css);

  final b = StringBuffer();
  b.writeln('// GENERATED by tool/wash_atmosphere/generate.dart');
  b.writeln("import 'dart:ui' show Color;");
  b.writeln();
  b.writeln('class WashAtmosphereTokens {');
  b.writeln('  const WashAtmosphereTokens({');
  b.writeln('    required this.washA,');
  b.writeln('    required this.washB,');
  b.writeln('    required this.washC,');
  b.writeln('    required this.paperFiber,');
  b.writeln('    required this.pigmentGrain,');
  b.writeln('    required this.inkBorder,');
  b.writeln('    required this.inkMuted,');
  b.writeln('  });');
  b.writeln('  final Color washA;');
  b.writeln('  final Color washB;');
  b.writeln('  final Color washC;');
  b.writeln('  final Color paperFiber;');
  b.writeln('  final Color pigmentGrain;');
  b.writeln('  final Color inkBorder;');
  b.writeln('  final Color inkMuted;');
  b.writeln('}');
  b.writeln();
  b.writeln('Color _hex(String hex) {');
  b.writeln('  var h = hex.replaceAll("#", "");');
  b.writeln(r'  if (h.length == 6) h = "ff" + h;');
  b.writeln('  return Color(int.parse(h, radix: 16));');
  b.writeln('}');
  b.writeln();
  b.writeln(
    'final Map<String, WashAtmosphereTokens> kWashAtmosphereByTheme = {',
  );
  for (final t in themes.entries) {
    b.writeln("  '${t.key}': WashAtmosphereTokens(");
    b.writeln('    washA: _hex("${t.value['washA']}"),');
    b.writeln('    washB: _hex("${t.value['washB']}"),');
    b.writeln('    washC: _hex("${t.value['washC']}"),');
    b.writeln('    paperFiber: _hex("${t.value['paperFiber']}"),');
    b.writeln('    pigmentGrain: _hex("${t.value['pigmentGrain']}"),');
    b.writeln('    inkBorder: _hex("${t.value['inkBorder']}"),');
    b.writeln('    inkMuted: _hex("${t.value['inkMuted']}"),');
    b.writeln('  ),');
  }
  b.writeln('};');

  File(outPath).parent.createSync(recursive: true);
  File(outPath).writeAsStringSync(b.toString());
  print('Wrote ${themes.length} atmosphere themes to $outPath');
}

String _repoRoot() {
  var dir = Directory.current;
  while (true) {
    if (File('${dir.path}/package.json').existsSync()) return dir.path;
    final parent = dir.parent;
    if (parent.path == dir.path) return Directory.current.path;
    dir = parent;
  }
}

Map<String, Map<String, String>> _parseAtmosphere(String css) {
  final result = <String, Map<String, String>>{};
  final blockRe = RegExp(
    r'\[data-theme="([^"]+)"\]\s*\{([^}]+)\}',
    multiLine: true,
  );
  for (final m in blockRe.allMatches(css)) {
    final id = m.group(1)!;
    final body = m.group(2)!;
    String? pick(String name) {
      final re = RegExp('$name:\\s*(#[0-9a-fA-F]+)');
      return re.firstMatch(body)?.group(1);
    }

    final washA = pick('--wash-a');
    final washB = pick('--wash-b');
    final washC = pick('--wash-c');
    final paperFiber = pick('--paper-fiber');
    final pigmentGrain = pick('--pigment-grain');
    final inkBorder = pick('--ink-border');
    final inkMuted = pick('--ink-muted');
    if (washA == null || inkBorder == null) continue;
    result[id] = {
      'washA': washA,
      'washB': washB ?? washA,
      'washC': washC ?? washA,
      'paperFiber': paperFiber ?? washA,
      'pigmentGrain': pigmentGrain ?? inkMuted ?? inkBorder,
      'inkBorder': inkBorder,
      'inkMuted': inkMuted ?? inkBorder,
    };
  }
  return result;
}
