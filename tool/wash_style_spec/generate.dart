  b.writeln('  paddingX: ${input['paddingX']},');
  b.writeln('  paddingY: ${input['paddingY']},');
  b.writeln('  fontSize: ${input['fontSize']},');
  b.writeln('  borderRadius: ${input['borderRadius']},');
