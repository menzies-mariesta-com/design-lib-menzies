// ignore_for_file: avoid_print
import 'dart:convert';
import 'dart:io';

void main() {
  final root = _repoRoot();
  final jsonPath = '$root/tool/wash_style_spec/wash_daisy_metrics.json';
  final outPath =
      '$root/packages/menzies_design_wash_ui/lib/src/tokens/wash_style_spec.g.dart';

  final raw = jsonDecode(File(jsonPath).readAsStringSync()) as Map<String, dynamic>;
  final btn = raw['btn'] as Map<String, dynamic>;
  final btnSizes = raw['btnSizes'] as Map<String, dynamic>;
  final input = raw['input'] as Map<String, dynamic>;
  final tableRow = raw['tableRow'] as Map<String, dynamic>;

  final b = StringBuffer();
  b.writeln('// GENERATED by tool/wash_style_spec/generate.dart');
  b.writeln();
  b.writeln('class WashBtnMetrics {');
  b.writeln('  const WashBtnMetrics({');
  b.writeln('    required this.paddingX,');
  b.writeln('    required this.minHeight,');
  b.writeln('    required this.fontSize,');
  b.writeln('    required this.fontWeight,');
  b.writeln('    required this.borderRadius,');
  b.writeln('    required this.borderWidth,');
  b.writeln('  });');
  b.writeln('  final double paddingX;');
  b.writeln('  final double minHeight;');
  b.writeln('  final double fontSize;');
  b.writeln('  final double fontWeight;');
  b.writeln('  final double borderRadius;');
  b.writeln('  final double borderWidth;');
  b.writeln('}');
  b.writeln();
  b.writeln('class WashInputMetrics {');
  b.writeln('  const WashInputMetrics({');
  b.writeln('    required this.minHeight,');
  b.writeln('    required this.paddingX,');
  b.writeln('    required this.paddingY,');
  b.writeln('    required this.fontSize,');
  b.writeln('    required this.borderRadius,');
  b.writeln('    required this.borderWidth,');
  b.writeln('  });');
  b.writeln('  final double minHeight;');
  b.writeln('  final double paddingX;');
  b.writeln('  final double paddingY;');
  b.writeln('  final double fontSize;');
  b.writeln('  final double borderRadius;');
  b.writeln('  final double borderWidth;');
  b.writeln('}');
  b.writeln();
  b.writeln('const WashBtnMetrics kWashBtnDefault = WashBtnMetrics(');
  b.writeln('  paddingX: ${btn['paddingX']},');
  b.writeln('  minHeight: ${btn['minHeight']},');
  b.writeln('  fontSize: ${btn['fontSize']},');
  b.writeln('  fontWeight: ${btn['fontWeight']},');
  b.writeln('  borderRadius: ${btn['borderRadius']},');
  b.writeln('  borderWidth: ${btn['borderWidth']},');
  b.writeln(');');
  b.writeln();
  b.writeln('const Map<String, WashBtnMetrics> kWashBtnSizeMetrics = {');
  for (final e in btnSizes.entries) {
    final m = e.value as Map<String, dynamic>;
    b.writeln("  '${e.key}': WashBtnMetrics(");
    b.writeln('    paddingX: ${m['paddingX']},');
    b.writeln('    minHeight: ${m['minHeight']},');
    b.writeln('    fontSize: ${m['fontSize']},');
    b.writeln('    fontWeight: ${btn['fontWeight']},');
    b.writeln('    borderRadius: ${btn['borderRadius']},');
