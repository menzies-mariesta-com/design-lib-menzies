#!/usr/bin/env node
/**
 * Sync datetime primitives from packages/menzies-design-wash-ui → apps/demo/src/plain.
 * Run from repo root: node tool/sync_datetime_primitives.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const pkg = resolve(root, 'packages/menzies-design-wash-ui/src/primitives')
const plainCal = resolve(root, 'apps/demo/src/plain/calendar')
const plainTime = resolve(root, 'apps/demo/src/plain/time')

const header =
  '/** AUTO-GENERATED by tool/sync_datetime_primitives.mjs — edit package source, then re-run sync. */\n'

function toPlain(content, rules) {
  let out = content
  for (const [from, to] of rules) {
    out = out.split(from).join(to)
  }
  out = out.replace(/from '\.\.\/icons'/g, "from '@menzies-mariesta-com/menzies-design-wash-ui/icons'")
  out = out.replace(/from '\.\/WashCalendar'/g, "from './CalendarMonth'")
  out = out.replace(/from '\.\/WashTimePicker'/g, "from '../time/TimeClockDial'")
  return header + out
}

const calendarRules = [
  ['WashCalendarProps', 'CalendarMonthProps'],
  ['WashCalendarDayMeta', 'CalendarMonthDayMeta'],
  ['WashCalendarMode', 'CalendarMonthMode'],
  ['WashCalendar', 'CalendarMonth'],
  ['./WashTimePicker', '../time/TimeClockDial'],
  ['WashTimePicker', 'TimeClockDial'],
]

const timeRules = [
  ['WashTimePickerProps', 'TimeClockDialProps'],
  ['WashTimePicker', 'TimeClockDial'],
]

const datePickerRules = [
  ['WashDatePickerProps', 'DatePickerProps'],
  ['WashDatePicker', 'DatePicker'],
  ['WashCalendar', 'CalendarMonth'],
  ["from './WashCalendar'", "from './CalendarMonth'"],
  ['{@link WashCalendar}', '{@link CalendarMonth}'],
]

const dateTimePickerRules = [
  ['WashDateTimePickerProps', 'DateTimePickerProps'],
  ['WashDateTimePicker', 'DateTimePicker'],
  ['WashCalendar', 'CalendarMonth'],
  ["from './WashCalendar'", "from './CalendarMonth'"],
]

const fieldsRules = [
  ['WashDateTimeFieldsProps', 'DateTimeFieldsProps'],
  ['WashDateTimeFields', 'DateTimeFields'],
  ['WashDatePickerProps', 'DatePickerProps'],
  ['WashDatePicker', 'DatePicker'],
  ['WashTimePickerProps', 'TimeClockDialProps'],
  ['WashTimePicker', 'TimeClockDial'],
  ["from './WashDatePicker'", "from './DatePicker'"],
  ["from './WashTimePicker'", "from '../time/TimeClockDial'"],
  ["from './TimeClockDial'", "from '../time/TimeClockDial'"],
  ['./TimeClockDial', '../time/TimeClockDial'],
  ['{@link WashDatePicker}', '{@link DatePicker}'],
  ['{@link WashTimePicker}', '{@link TimeClockDial}'],
]

const jobs = [
  [resolve(pkg, 'WashCalendar.tsx'), resolve(plainCal, 'CalendarMonth.tsx'), calendarRules],
  [resolve(pkg, 'WashTimePicker.tsx'), resolve(plainTime, 'TimeClockDial.tsx'), timeRules],
  [resolve(pkg, 'WashDatePicker.tsx'), resolve(plainCal, 'DatePicker.tsx'), datePickerRules],
  [
    resolve(pkg, 'WashDateTimePicker.tsx'),
    resolve(plainCal, 'DateTimePicker.tsx'),
    dateTimePickerRules,
  ],
  [
    resolve(pkg, 'WashDateTimeFields.tsx'),
    resolve(plainCal, 'DateTimeFields.tsx'),
    fieldsRules,
  ],
]

for (const [src, dest, rules] of jobs) {
  const raw = readFileSync(src, 'utf8')
  // Skip generated header if re-running on already synced? Source is always package.
  const body = raw.replace(/^\/\*\* AUTO-GENERATED[\s\S]*?\*\/\n/, '')
  writeFileSync(dest, toPlain(body, rules))
  console.log(`synced ${dest.replace(root + '/', '')}`)
}
