// ignore_for_file: avoid_print
import 'dart:io';

/// Copies Lucide 1.28.0 + @lucide/lab SVGs into menzies_design_wash_ui and
/// generates [wash_lucide_icon_names.g.dart].
///
/// Prerequisites (repo root):
///   npm install lucide-static@1.28.0 @lucide/lab@0.7.0
void main() {
  final repoRoot = _findRepoRoot();
  final pkgRoot = '$repoRoot/packages/menzies_design_wash_ui';
  final lucideSrc = Directory('$repoRoot/node_modules/lucide-static/icons');
  final labSrc = Directory('$repoRoot/node_modules/@lucide/lab/icons');
  final lucideDest = Directory('$pkgRoot/assets/icons/lucide');
  final labDest = Directory('$pkgRoot/assets/icons/lucide-lab');
  final outFile = File('$pkgRoot/lib/src/icons/wash_lucide_icon_names.g.dart');

  if (!lucideSrc.existsSync()) {
    stderr.writeln(
      'Missing ${lucideSrc.path}. Run: npm install lucide-static@1.28.0',
    );
    exit(1);
  }
  if (!labSrc.existsSync()) {
    stderr.writeln(
      'Missing ${labSrc.path}. Run: npm install @lucide/lab@0.7.0',
    );
    exit(1);
  }

  final lucideNames = _syncSvgDir(lucideSrc, lucideDest);
  final labNames = _syncSvgDir(labSrc, labDest);

  if (lucideNames.isEmpty) {
    stderr.writeln('No Lucide icons copied.');
    exit(1);
  }

  _writeNamesFile(outFile, lucideNames, labNames);
  print(
    'Lucide icons: ${lucideNames.length}, lab: ${labNames.length} -> ${outFile.path}',
  );
}

List<String> _syncSvgDir(Directory src, Directory dest) {
  if (dest.existsSync()) {
    dest.deleteSync(recursive: true);
  }
  dest.createSync(recursive: true);

  final names = <String>[];
  for (final entity in src.listSync().whereType<File>()) {
    if (!entity.path.endsWith('.svg')) continue;
    final base = entity.uri.pathSegments.last;
    final name = base.replaceAll(RegExp(r'\.svg$'), '');
    final target = File('${dest.path}/$base');
    entity.copySync(target.path);
    names.add(name);
  }
  names.sort();
  return names;
}

void _writeNamesFile(
  File out,
  List<String> lucideNames,
  List<String> labNames,
) {
  final b = StringBuffer();
  b.writeln('// GENERATED by tool/wash_lucide/generate.dart — do not edit.');
  b.writeln();
  b.writeln('/// Kebab-case Lucide icon names (lucide-static 1.28.0).');
  b.writeln('const List<String> washLucideIconNames = <String>[');
  for (final n in lucideNames) {
    b.writeln("  '$n',");
  }
  b.writeln('];');
  b.writeln();
  b.writeln('/// Lucide Lab icon names (@lucide/lab).');
  b.writeln('const List<String> washLucideLabIconNames = <String>[');
  for (final n in labNames) {
    b.writeln("  '$n',");
  }
  b.writeln('];');
  b.writeln();
  b.writeln('final Set<String> washLucideIconNameSet =');
  b.writeln('    Set<String>.unmodifiable(washLucideIconNames);');
  b.writeln();
  b.writeln('final Set<String> washLucideLabIconNameSet =');
  b.writeln('    Set<String>.unmodifiable(washLucideLabIconNames);');
  out.parent.createSync(recursive: true);
  out.writeAsStringSync(b.toString());
}

String _findRepoRoot() {
  var dir = Directory.current;
  while (true) {
    if (File('${dir.path}/package.json').existsSync() &&
        Directory('${dir.path}/packages/menzies_design_wash_ui').existsSync()) {
      return dir.path;
    }
    final parent = dir.parent;
    if (parent.path == dir.path) {
      throw StateError('Could not find monorepo root from ${Directory.current.path}');
    }
    dir = parent;
  }
}
