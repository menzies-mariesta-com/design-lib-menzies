/**
 * Snapshot monorepo Wash UI sources into src/data/embedded-snapshot.ts
 * so the published MCP package works without WASH_UI_REPO_ROOT.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const pkgRoot = resolve(__dirname, '..')
const repoRoot = resolve(pkgRoot, '../..')
const washSrc = join(repoRoot, 'packages/menzies-design-wash-ui/src')
const outFile = join(pkgRoot, 'src/data/embedded-snapshot.ts')

function readSafe(path) {
  try {
    if (!existsSync(path)) return null
    return readFileSync(path, 'utf8')
  } catch {
    return null
  }
}

function parsePigmentThemes(src) {
  if (!src) return []
  const themes = []
  const blockRe =
    /\{\s*id:\s*'([^']+)',\s*label:\s*'([^']+)',\s*note:\s*'([^']*)',\s*swatch:\s*'([^']+)'/g
  let m
  while ((m = blockRe.exec(src))) {
    themes.push({ id: m[1], label: m[2], note: m[3], swatch: m[4] })
  }
  return themes
}

function parseBrands(src) {
  if (!src) return []
  const brands = []
  const re = /^\s*([a-z0-9]+):\s*'([^']+)'/gm
  let m
  while ((m = re.exec(src))) {
    brands.push({ slug: m[1], exportName: m[2] })
  }
  return brands
}

function listTsxNames(dir) {
  if (!existsSync(dir)) return []
  return readdirSync(dir)
    .filter((f) => f.endsWith('.tsx') && f !== 'index.ts')
    .map((f) => f.replace(/\.tsx$/, ''))
    .sort()
}

function excerptSource(src) {
  if (!src) return null
  const typeMatch = src.match(
    /export type \w+Props[\s\S]*?=[\s\S]*?(?=\nexport |\nconst |\nfunction )/m,
  )
  const fnMatch = src.match(/export (?:const|function) \w+[\s\S]{0,800}/m)
  const parts = [typeMatch?.[0]?.trim(), fnMatch?.[0]?.trim()].filter(Boolean)
  return (parts.join('\n\n') || src.slice(0, 1200)).slice(0, 2500)
}

const SOURCE_SNIPPET_PATHS = [
  'primitives/Button.tsx',
  'primitives/Input.tsx',
  'primitives/Textarea.tsx',
  'primitives/Checkbox.tsx',
  'primitives/Toggle.tsx',
  'primitives/Select.tsx',
  'primitives/Dialog.tsx',
  'primitives/Tooltip.tsx',
  'primitives/Loading.tsx',
  'components/Card.tsx',
  'components/Accordion.tsx',
  'components/Tabs.tsx',
  'components/ThemeSwitcher.tsx',
  'components/FloatingPanel.tsx',
  'WashProvider.tsx',
]

if (!existsSync(join(washSrc, 'theme/themes.ts'))) {
  console.error(
    `[wash-ui-mcp embed] Missing Wash UI source at ${washSrc}. Run from the design-lib monorepo.`,
  )
  process.exit(1)
}

const themesTs = readSafe(join(washSrc, 'theme/themes.ts'))
const themesCss = readSafe(join(washSrc, 'styles/themes.css')) ?? ''
const slugMap = readSafe(join(washSrc, 'icons/brands/slugMap.ts'))

const sourceSnippets = {}
for (const rel of SOURCE_SNIPPET_PATHS) {
  const excerpt = excerptSource(readSafe(join(washSrc, rel)))
  if (excerpt) {
    sourceSnippets[rel] = {
      path: `packages/menzies-design-wash-ui/src/${rel}`,
      excerpt,
    }
  }
}

const snapshot = {
  generatedAt: new Date().toISOString(),
  pigmentThemes: parsePigmentThemes(themesTs),
  themesCss,
  brands: parseBrands(slugMap),
  primitives: listTsxNames(join(washSrc, 'primitives')),
  components: listTsxNames(join(washSrc, 'components')),
  sourceSnippets,
}

mkdirSync(dirname(outFile), { recursive: true })
writeFileSync(
  outFile,
  `/* Auto-generated by scripts/embed-snapshot.mjs. Do not edit. */
export type EmbeddedPigmentTheme = {
  id: string
  label: string
  note?: string
  swatch?: string
}

export type EmbeddedBrand = { slug: string; exportName: string }

export type EmbeddedSourceSnippet = { path: string; excerpt: string }

export type EmbeddedWashUiSnapshot = {
  generatedAt: string
  pigmentThemes: EmbeddedPigmentTheme[]
  themesCss: string
  brands: EmbeddedBrand[]
  primitives: string[]
  components: string[]
  sourceSnippets: Record<string, EmbeddedSourceSnippet>
}

export const embeddedSnapshot: EmbeddedWashUiSnapshot = ${JSON.stringify(snapshot, null, 2)}
`,
)

console.log(
  `[wash-ui-mcp embed] Wrote ${outFile} (${snapshot.pigmentThemes.length} pigments, ${snapshot.brands.length} brands, css ${themesCss.length} chars)`,
)
