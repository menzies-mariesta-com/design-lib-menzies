/**
 * Regenerates src/styles/daisy-inventory.html from the installed daisyUI package.
 * Run after upgrading daisyui so dist/styles.css keeps force-including every component.
 *
 *   node packages/menzies-design-wash-ui/scripts/generate-daisy-inventory.mjs
 */
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { createRequire } from 'node:module'
import { fileURLToPath } from 'node:url'

const require = createRequire(import.meta.url)
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const daisyRoot = dirname(require.resolve('daisyui/package.json'))

const classRe = /(?<![a-zA-Z0-9_-])\.([a-z][a-z0-9-]*)/g
const classes = new Set()

function walk(dir) {
  if (!existsSync(dir)) return
  for (const name of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, name.name)
    if (name.isDirectory()) walk(p)
    else if (name.name === 'object.js') {
      const text = readFileSync(p, 'utf8')
      for (const m of text.matchAll(classRe)) {
        const c = m[1]
        if (!c.startsWith('tw-')) classes.add(c)
      }
    }
  }
}

walk(join(daisyRoot, 'components'))
walk(join(daisyRoot, 'utilities'))

const sorted = [...classes].sort()
const out = join(root, 'src/styles/daisy-inventory.html')
const html = `<!-- DaisyUI class inventory for Wash CSS builds.
     Regenerated by scripts/generate-daisy-inventory.mjs from daisyUI ${
       JSON.parse(readFileSync(join(daisyRoot, 'package.json'), 'utf8')).version
     }.
     Tailwind v4 only emits daisyUI plugin components when their class names
     appear in scanned sources. This file force-includes the full component set
     so dist/styles.css ships gallery-complete styles without a separate Daisy install. -->
<div class="${sorted.join(' ')}"></div>
`
writeFileSync(out, html)
console.log(`Wrote ${out} (${sorted.length} classes)`)
