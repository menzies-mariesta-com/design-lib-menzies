/**
 * Snapshot Compose Kotlin sources into src/data/embedded-snapshot.ts
 * so the published MCP package works without WASH_UI_REPO_ROOT.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const pkgRoot = resolve(__dirname, '..')
const repoRoot = resolve(pkgRoot, '../..')
const kotlinRoot = join(
  repoRoot,
  'packages/menzies-design-wash-compose/src/commonMain/kotlin/com/mariesta/menzies/washui',
)
const outFile = join(pkgRoot, 'src/data/embedded-snapshot.ts')

function readSafe(path) {
  try {
    if (!existsSync(path)) return null
    return readFileSync(path, 'utf8')
  } catch {
    return null
  }
}

function listKtNames(dir) {
  if (!existsSync(dir)) return []
  return readdirSync(dir)
    .filter((f) => f.endsWith('.kt'))
    .map((f) => f.replace(/\.kt$/, ''))
    .sort()
}

function parsePigments(src) {
  if (!src) return []
  const enumBody = src.match(
    /enum class WashPigment\s*\{([\s\S]*?)(?:;|\n\s*val |\n\s*companion )/m,
  )
  if (!enumBody) return []
  return enumBody[1]
    .split(/[\s,]+/)
    .map((s) => s.trim())
    .filter((s) => /^[a-z][a-z0-9_]*$/.test(s))
}

function parseComposable(src, relativeFile) {
  if (!src) return null
  const pkgMatch = src.match(/^package\s+([\w.]+)/m)
  const packagePath = pkgMatch?.[1] ?? 'com.mariesta.menzies.washui'
  const kdocMatch = src.match(/\/\*\*([\s\S]*?)\*\/\s*(?:@Composable\s+)?(?:public\s+)?fun\s+(\w+)/)
  const funMatch = src.match(
    /(?:@Composable\s+)?(?:public\s+)?fun\s+(\w+)\s*\(([\s\S]*?)\)\s*(?::\s*[\w.<>,\s?]+)?\s*\{/,
  )
  if (!funMatch) return null

  const name = funMatch[1]
  const params = funMatch[2]
    .split(',')
    .map((p) => p.replace(/\s+/g, ' ').trim())
    .filter((p) => p && !p.startsWith('//'))
    .map((p) => {
      const cleaned = p.replace(/\/\*[\s\S]*?\*\//g, '').trim()
      const m = cleaned.match(/^(\w+)\s*:/)
      return m ? `${m[1]}: ${cleaned.slice(m[0].length).trim().slice(0, 80)}` : cleaned.slice(0, 100)
    })
    .filter(Boolean)

  const kdoc = kdocMatch?.[1]
    ?.replace(/^\s*\*\s?/gm, '')
    .trim()
    .slice(0, 500)

  return {
    name,
    packagePath,
    relativeFile,
    params,
    kdoc,
    excerpt: (funMatch[0] + '\n  …\n}').slice(0, 1500),
  }
}

if (!existsSync(join(kotlinRoot, 'theme/WashPigment.kt'))) {
  console.error(
    `[wash-compose-mcp embed] Missing Compose source at ${kotlinRoot}. Run from the design-lib monorepo.`,
  )
  process.exit(1)
}

const primitives = listKtNames(join(kotlinRoot, 'primitives'))
const components = listKtNames(join(kotlinRoot, 'components'))
const lucide = listKtNames(join(kotlinRoot, 'icons/lucide'))
const brands = listKtNames(join(kotlinRoot, 'icons/brands'))
const pigments = parsePigments(readSafe(join(kotlinRoot, 'theme/WashPigment.kt')))

const composables = {}
const candidates = [
  ...primitives.map((n) => ({
    file: join(kotlinRoot, 'primitives', `${n}.kt`),
    rel: `primitives/${n}.kt`,
  })),
  ...components.map((n) => ({
    file: join(kotlinRoot, 'components', `${n}.kt`),
    rel: `components/${n}.kt`,
  })),
  {
    file: join(kotlinRoot, 'WashProvider.kt'),
    rel: 'WashProvider.kt',
  },
  {
    file: join(kotlinRoot, 'icons/WashIcons.kt'),
    rel: 'icons/WashIcons.kt',
  },
]

for (const c of candidates) {
  const parsed = parseComposable(readSafe(c.file), c.rel)
  if (parsed) {
    composables[parsed.name] = parsed
    const base = c.rel.split('/').pop()?.replace(/\.kt$/, '')
    if (base && !composables[base]) composables[base] = parsed
  }
}

const snapshot = {
  generatedAt: new Date().toISOString(),
  pigments,
  lucide,
  brands,
  primitives,
  components,
  composables,
}

mkdirSync(dirname(outFile), { recursive: true })
writeFileSync(
  outFile,
  `/* Auto-generated by scripts/embed-snapshot.mjs. Do not edit. */
export type EmbeddedComposable = {
  name: string
  packagePath: string
  relativeFile: string
  params: string[]
  kdoc?: string
  excerpt: string
}

export type EmbeddedComposeSnapshot = {
  generatedAt: string
  pigments: string[]
  lucide: string[]
  brands: string[]
  primitives: string[]
  components: string[]
  composables: Record<string, EmbeddedComposable>
}

export const embeddedSnapshot: EmbeddedComposeSnapshot = ${JSON.stringify(snapshot, null, 2)}
`,
)

console.log(
  `[wash-compose-mcp embed] Wrote ${outFile} (${pigments.length} pigments, ${lucide.length} lucide, ${Object.keys(composables).length} composables)`,
)
